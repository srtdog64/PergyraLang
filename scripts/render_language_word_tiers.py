#!/usr/bin/env python3
"""Render the documentation tiers of the language words.

The tier table (word, tier) is checked against the canonical language-word
registry: every registry word has exactly one tier, 1 or 2, in registry order,
and the table names no other word. The rendered page groups the words by tier
and by the registry's primary axis. A tier is documentation only; the compiler
does not read it.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import render_language_keyword_registry as registry  # noqa: E402

AXES = (
    ("PGY_KEYWORD_AXIS_GENERAL", "일반"),
    ("PGY_KEYWORD_AXIS_TYPE_CONTRACT", "타입·계약"),
    ("PGY_KEYWORD_AXIS_EXECUTION", "실행·제어"),
    ("PGY_KEYWORD_AXIS_RESOURCE", "자원·소유"),
    ("PGY_KEYWORD_AXIS_DOMAIN", "도메인"),
)
TIER_TITLES = {
    1: "1급: 핵심",
    2: "2급: 도메인이 커질 때",
}


def load_tiers(path: Path, words: list[str]) -> dict[str, int]:
    rows: list[tuple[str, int]] = []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 2 or parts[1] not in ("1", "2"):
            raise SystemExit(f"{path}:{number}: expected 'word<TAB>1' or 'word<TAB>2'")
        rows.append((parts[0], int(parts[1])))
    listed = [word for word, _ in rows]
    if listed != words:
        missing = sorted(set(words) - set(listed))
        unknown = sorted(set(listed) - set(words))
        raise SystemExit(
            f"{path}: the tier table must list every registry word once, in registry order; "
            f"missing={missing} unknown={unknown}"
        )
    return dict(rows)


def render(rows: list[registry.KeywordRow], tiers: dict[str, int]) -> str:
    out = [
        "<!-- Generated by scripts/render_language_word_tiers.py from "
        "docs/language/language_word_tiers.tsv and "
        "src/lexer/language_keyword_registry.def. Do not edit. -->",
        "",
        "# 언어 단어 등급: 1급과 2급",
        "",
        "어떤 단어도 필수가 아니다. 처음에는 1급만으로 일반 프로그램을 쓴다. "
        "2급은 도메인 규칙, 권한, 자원 경계, 동시성, 실패 보상이 코드에 "
        "필요해질 때 꺼내 쓰며, 쓰지 않아도 된다.",
        "",
        "등급은 문서 분류이고 언어 규칙이 아니다. 컴파일러는 이 표를 읽지 않는다. "
        "철자, 클래스, 축은 [레지스트리](../../src/lexer/language_keyword_registry.def)가 "
        "소유한다. 등급을 바꾸려면 `docs/language/language_word_tiers.tsv`를 고치고 "
        "렌더러를 `--write`로 다시 돌린다.",
        "",
        "`(c)`는 예약어가 아닌 단어(contextual 또는 soft)로, 식별자로도 쓸 수 있다.",
    ]
    for tier in (1, 2):
        chosen = [row for row in rows if tiers[row.spelling] == tier]
        out += ["", f"## {TIER_TITLES[tier]} ({len(chosen)})", "", "| 축 | 단어 |", "|---|---|"]
        for axis, title in AXES:
            words = [
                f"`{row.spelling}`" + ("" if row.keyword_class == registry.RESERVED else " (c)")
                for row in chosen
                if row.axis == axis
            ]
            if words:
                out.append(f"| {title} | {' '.join(words)} |")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("registry", type=Path)
    parser.add_argument("tiers", type=Path)
    parser.add_argument("output", type=Path)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()

    rows = registry.load_rows(args.registry)
    known_axes = {axis for axis, _ in AXES}
    for row in rows:
        if row.axis not in known_axes:
            raise SystemExit(f"registry word {row.spelling} has an axis this page does not render: {row.axis}")
    tiers = load_tiers(args.tiers, [row.spelling for row in rows])
    expected = render(rows, tiers)
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != expected:
            raise SystemExit(
                f"language word tier page drifted: {args.output.as_posix()}; regenerate with "
                f"{Path(__file__).as_posix()} {args.registry.as_posix()} "
                f"{args.tiers.as_posix()} {args.output.as_posix()} --write"
            )
        return 0
    args.output.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
