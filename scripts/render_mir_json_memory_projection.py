#!/usr/bin/env python3
"""Derive a pure MIR JSON sink from the authoritative sequential file writers.

This is a bounded effect specialization, not a Pergyra compiler. The selected
row functions have one scalar output handle. Only that formal and the known
write operations change; all framing, row selection and refusal logic stay
owned by the original Pergyra functions. Compilation and byte parity validate
the generated consumer; --check prevents it becoming a second schema owner.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MIR = ROOT / "src/self_hosted/mir"
SOURCES = {
    "program_json_artifact_writer_owner.pgy": "program_json_memory_projection.pgy",
    "instruction_json_artifact_writer_owner.pgy": "instruction_json_memory_projection.pgy",
    "expression_identity_json_projection_owner.pgy": "expression_identity_json_memory_projection.pgy",
    "local_ref_json_projection_owner.pgy": "local_ref_json_memory_projection.pgy",
    "runtime_call_abi_json_projection_owner.pgy": "runtime_call_abi_json_memory_projection.pgy",
    "intent_execution_json_projection_owner.pgy": "intent_execution_json_memory_projection.pgy",
}
TOKEN = re.compile(r'''"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|//[^\n]*|/\*[\s\S]*?\*/|[A-Za-z_]\w*''')
FUNCTION = re.compile(r"\bfunc\s+([A-Za-z_]\w*)\s*\(")
OUTPUT = re.compile(r"\boutput\s*:\s*Int\b")


def masked(source: str) -> str:
    def erase(match: re.Match) -> str:
        token = match.group()
        if token.startswith(('"', "'", "/")):
            return ''.join('\n' if char == '\n' else ' ' for char in token)
        return token
    return TOKEN.sub(erase, source)


def row_functions(source: str) -> dict[str, str]:
    code = masked(source)
    result = {}
    for match in FUNCTION.finditer(code):
        name = match[1]
        if not name.endswith("WriteFile") or name == "SelfMirProgramJsonWriteFile":
            continue
        opening = code.index("{", match.end())
        depth, cursor = 1, opening + 1
        while cursor < len(code) and depth:
            if code[cursor] == '{':
                depth += 1
            elif code[cursor] == '}':
                depth -= 1
            cursor += 1
        if depth:
            raise ValueError(f"{name}: unclosed row function")
        header = code[match.start():opening]
        if len(OUTPUT.findall(header)) != 1 or 'with caps' in header:
            raise ValueError(f"{name}: unsupported output formal/effect declaration")
        body = code[opening:cursor]
        if re.search(r'\b(?:let|var)\s+output\b', body):
            raise ValueError(f"{name}: output formal is shadowed")
        result[name] = source[match.start():cursor]
    if not result:
        raise ValueError("schema owner contains no sequential row functions")
    return result


def specialize(source: str, names: dict[str, str]) -> str:
    opening = masked(source).index('{')
    formal = OUTPUT.search(masked(source), 0, opening)
    if formal is None:
        raise ValueError("missing output formal")
    source = source[:formal.start()] + 'inout fragments: Array<String>' + source[formal.end():]

    def replace(match: re.Match) -> str:
        token = match.group()
        if token.startswith(('"', "'", "/")):
            return token
        if token == 'output':
            return 'fragments'
        return names.get(token, token)
    return TOKEN.sub(replace, source)


def render() -> dict[str, str]:
    functions = {owner: row_functions((MIR / owner).read_text(encoding='utf-8'))
                 for owner in SOURCES}
    owners = {}
    for owner, rows in functions.items():
        for name in rows:
            if name in owners:
                raise ValueError(f"duplicate writer identity {name}")
            owners[name] = owner
    names = {name: name.removesuffix('WriteFile') + 'WriteMemory' for name in owners}
    names.update({
        'CompilerArtifactWrite': 'JsonProjectionAppend',
        'JsonStringLiteralWriteFile': 'JsonStringLiteralAppend',
        'JsonOwnedFragmentWriteFile': 'JsonOwnedFragmentAppend',
    })
    generated = {}
    for owner, rows in functions.items():
        dependencies = set()
        for source in rows.values():
            for match in TOKEN.finditer(source):
                target = owners.get(match.group())
                if target is not None and target != owner:
                    dependencies.add(SOURCES[target])
        imports = [owner, *sorted(dependencies)]
        text = ('// Generated by scripts/render_mir_json_memory_projection.py. Do not edit.\n'
                f'// Schema owner: {owner}; only output effects are specialized.\n\n'
                + '\n'.join(f'import "{path}";' for path in imports) + '\n\n'
                + '\n\n'.join(specialize(source, names) for source in rows.values()) + '\n')
        if owner == 'program_json_artifact_writer_owner.pgy':
            if 'SelfMirProgramJsonRowsWriteFile' not in rows:
                raise ValueError('missing authoritative program row writer')
            text += '''
func SelfMirProgramJson(facts: SelfMirProgramFacts) -> String {
    if !SelfMirProgramFactsReady(facts) { return ""; }
    var fragments: Array<String> = [];
    var json: String = "";
    if SelfMirProgramJsonRowsWriteMemory(facts, fragments) {
        json = StringJoin(fragments, "");
    }
    // One cleanup exit for success and rejection; StringJoin copies bytes.
    ArrayDropOwnedStrings(fragments);
    return json;
}
'''
        generated[SOURCES[owner]] = text
    return generated


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for name, expected in render().items():
        path = MIR / name
        if args.write:
            path.write_text(expected, encoding='utf-8', newline='\n')
        elif not path.is_file() or path.read_text(encoding='utf-8') != expected:
            raise SystemExit(f'MIR JSON memory projection drift: {path.relative_to(ROOT)}; regenerate with --write')
    print('[mir-json-memory-projection] six pure projections match their file-schema owners')


if __name__ == '__main__':
    main()
