#!/usr/bin/env python3
"""Project src/common/target_profile.def into the self-host compiler.

The native compiler includes the X-macro rows directly. The self-host
compiler reads this generated projection; `--check` fails when it drifts.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re

ROW = re.compile(
    r'^PGY_TARGET_PROFILE\(\s*([A-Z0-9_]+)\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,'
    r"\s*(\d+)\s*,\s*(\d+)\s*,\s*([01])\s*\)\s*$"
)
FIELDS = (
    ("Name", "String", 0),
    ("LlvmTriple", "String", 1),
    ("CTarget", "String", 2),
    ("ObjectFormat", "String", 3),
    ("PointerBitsAt", "Int", 4),
    ("PointerAlignAt", "Int", 5),
    ("LittleEndianAt", "Bool", 6),
)


def load_rows(path: Path) -> list[tuple[str, ...]]:
    text = re.sub(r"/\*.*?\*/", "", path.read_text(encoding="utf-8"), flags=re.DOTALL)
    rows: list[tuple[str, ...]] = []
    for number, line in enumerate(text.splitlines(), start=1):
        line = line.strip()
        if not line:
            continue
        match = ROW.match(line)
        if match is None:
            raise SystemExit(f"{path}:{number}: not a PGY_TARGET_PROFILE row: {line}")
        rows.append(match.groups())
    if not rows:
        raise SystemExit(f"{path}: no target profile rows")
    if len({row[0] for row in rows}) != len(rows):
        raise SystemExit(f"{path}: duplicate target profile name")
    return rows


def literal(kind: str, value: str) -> str:
    if kind == "String":
        return f'"{value}"'
    if kind == "Bool":
        return "true" if value == "1" else "false"
    return value


def render(rows: list[tuple[str, ...]]) -> str:
    out = [
        "// Generated by scripts/render_target_profile_rows.py from",
        "// src/common/target_profile.def. Do not edit.",
        "// The compilation targets of registry row target.capability_profile.",
        "",
        f"func CompilerTargetProfileRowCount() -> Int {{ return {len(rows)}; }}",
    ]
    for suffix, kind, column in FIELDS:
        empty = {"String": '""', "Int": "0", "Bool": "false"}[kind]
        out += ["", f"func CompilerTargetProfile{suffix}(row: Int) -> {kind} {{"]
        for index, row in enumerate(rows):
            out.append(f"    if row == {index} {{ return {literal(kind, row[column])}; }}")
        out += [f"    return {empty};", "}"]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("definition", type=Path)
    parser.add_argument("output", type=Path)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    expected = render(load_rows(args.definition))
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != expected:
            raise SystemExit(
                f"target profile projection drifted: {args.output.as_posix()}; regenerate with "
                f"scripts/render_target_profile_rows.py {args.definition.as_posix()} "
                f"{args.output.as_posix()} --write"
            )
        return 0
    args.output.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
